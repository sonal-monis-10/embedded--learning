# PlatformIO pre-build script: firmware.env -> generated/build_config.h
#
# firmware.env (git-ignored) holds KEY="value" lines with JSON strings.
# The values become C string constants in a header inside .pio/, so they
# never appear on a compiler command line or in the build log.
#
# Fails the build when a value is missing, or when a URL is not https/wss
# (set DEV_INSECURE=1 in the shell to allow http/ws for a local backend).

import json
import os
import re
import subprocess
from datetime import datetime, timezone

Import("env")  # noqa: F821  (provided by PlatformIO)

REQUIRED = ["WIFI_SSID", "WIFI_PASS", "PROVISION_KEY", "API_URL", "BROKER_URL"]
PLACEHOLDER = re.compile(r"TYPE-|PASTE-|<host>")
FW_VERSION = "0.1.0"


def fail(message):
    print(f"\n*** firmware.env: {message}\n")
    env.Exit(1)  # noqa: F821


def read_env_file(path):
    if not os.path.isfile(path):
        fail(f"{path} not found. Create it first (see docs/plan/phase-1-foundation.md, step 4).")
    values = {}
    with open(path, encoding="utf-8") as f:
        for number, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            key, sep, raw = line.partition("=")
            if not sep:
                fail(f"line {number}: expected KEY=\"value\"")
            try:
                value = json.loads(raw.strip())
            except json.JSONDecodeError:
                fail(f"line {number} ({key.strip()}): the value must be in double quotes")
            if not isinstance(value, str):
                fail(f"line {number} ({key.strip()}): the value must be a string")
            values[key.strip()] = value
    return values


def check(values):
    for key in REQUIRED:
        if not values.get(key):
            fail(f"{key} is missing or empty")
        if PLACEHOLDER.search(values[key]):
            fail(f"{key} still has its placeholder; fill it in")
    insecure = os.environ.get("DEV_INSECURE") == "1"
    schemes = {"API_URL": ("https://", "http://"), "BROKER_URL": ("wss://", "ws://")}
    for key, (secure, plain) in schemes.items():
        url = values[key]
        if url.startswith(secure) or (insecure and url.startswith(plain)):
            continue
        fail(f"{key} must start with {secure}" + ("" if insecure else " (DEV_INSECURE=1 allows " + plain + ")"))


def git_sha(project_dir):
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=project_dir, capture_output=True, text=True, check=True,
        )
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def c_string(value):
    # A JSON string is also a valid C string literal for these values.
    return json.dumps(value)


project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
values = read_env_file(os.environ.get("FIRMWARE_ENV", os.path.join(project_dir, "firmware.env")))
check(values)

defines = {
    "WIFI_SSID": values["WIFI_SSID"],
    "WIFI_PASS": values["WIFI_PASS"],
    "PROVISION_KEY": values["PROVISION_KEY"],
    "API_URL": values["API_URL"].rstrip("/"),
    "BROKER_URL": values["BROKER_URL"],
    "FW_VERSION": FW_VERSION,
    "FW_GIT_SHA": git_sha(project_dir),
}
lines = ["// Generated by scripts/gen_config.py from firmware.env. Do not edit.", "#pragma once", ""]
lines += [f"#define {name} {c_string(value)}" for name, value in defines.items()]
header = "\n".join(lines) + "\n"
# The build time changes on every build; keep it out of the comparison so
# an unchanged firmware.env does not force a rebuild.
built_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)
out_file = os.path.join(out_dir, "build_config.h")
previous = open(out_file, encoding="utf-8").read() if os.path.isfile(out_file) else None
if previous is None or not previous.startswith(header):
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(header + f'#define FW_BUILT_AT "{built_at}"\n')
    os.chmod(out_file, 0o600)

env.Append(CPPPATH=[out_dir])  # noqa: F821
